CREATE SEQUENCE DNEVNIK_ID AS INTEGER START WITH 1 INCREMENT BY 1;
GRANT ALL ON SEQUENCE DNEVNIK_ID TO "aplikacija";

create table dnevnik (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	vrijeme timestamp,
	korisnik char (20),
	adresaRacunala varchar (99),
	ipAdresaRacunala varchar (50),
	nazivOS varchar (30),
	verzijaVM varchar (20),
	url varchar (512),
	opisRada varchar (512),
	FOREIGN KEY (korisnik) REFERENCES korisnici (korisnik)	
); 

GRANT SELECT, UPDATE, INSERT, DELETE ON TABLE dnevniK TO "aplikacija";

CREATE SEQUENCE RACUN_ID AS INTEGER START WITH 1 INCREMENT BY 1;
GRANT ALL ON SEQUENCE RACUN_ID TO "aplikacija";

create table racun (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	vrijeme timestamp,
	korisnik char (20),
	brojStavki INTEGER,
	iznos FLOAT,
	FOREIGN KEY (korisnik) REFERENCES korisnici (korisnik)	
); 

GRANT SELECT, UPDATE, INSERT, DELETE ON TABLE racun TO "aplikacija";

CREATE SEQUENCE RACUNSTAVKA_ID AS INTEGER START WITH 1 INCREMENT BY 1;
GRANT ALL ON SEQUENCE RACUNSTAVKA_ID TO "aplikacija";

create table racunstavka (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	racunId INTEGER,
	putnikIme char (20),
	putnikIPrezime char (20),
	rezervacija varchar (30),
	iznos FLOAT,
	FOREIGN KEY (racunId) REFERENCES racun (id)	
	
